#!/usr/bin/env node
// Regenerate API parameter decoding metadata from the pinned Go AST, without interpreting source text.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const schema = JSON.parse(execFileSync("go", ["run", path.join(root, "tools/gen-api-params/schema.go"), "--",
    path.join(root, "ts-ref/tsc/internal/api/proto.go")], { encoding: "utf8", env: { ...process.env, GOWORK: "off" } }));
const external = new Map([
    ["project.Handle", "U64"], ["project.ID", "Str"], ["project.SyntheticProjectID", "Str"],
    ["tspath.Path", "Str"], ["tspath.PathKey", "Str"], ["tspath.RootedFilePath", "Str"],
    ["tspath.RootedDirectoryPath", "Str"], ["core.ScriptKind", "I32"], ["core.UTF16Offset", "U32"],
    ["core.ResolutionMode", "I32"], ["diagnostics.Category", "U32"],
    ["json.Value", "Any"], ["packagejson.JSONValue", "Any"],
    // EnsurePrograms has a custom union decoder (true or a logical-ID array); the handler validates it.
    ["EnsurePrograms", "Any"],
    // Alias declared by api/module_resolution.go rather than proto.go.
    ["ResolutionMode", "I32"],
]);
const primitives = new Map([["string", "Str"], ["bool", "Bool"], ["int", "I64"], ["int32", "I32"],
    ["uint32", "U32"], ["uint64", "U64"], ["any", "Any"]]);
const base = value => value.startsWith("*") ? base(value.slice(1)) : value;
const kind = value => {
    const type = base(value);
    if (type === "DocumentIdentifier") return "Doc";
    if (type === "[]DocumentIdentifier") return "DocList";
    if (type.startsWith("[]")) return "Array";
    if (primitives.has(type)) return primitives.get(type);
    if (external.has(type)) return external.get(type);
    if (schema.aliases[type]) return kind(schema.aliases[type]);
    return "Object";
};
const fields = name => {
    const result = [];
    for (const field of schema.structs[name] ?? []) {
        if (field.embedded) result.push(...fields(base(field.type)));
        else result.push(field);
    }
    return result;
};
const emitField = field => {
    const type = base(field.type);
    const fieldKind = kind(type);
    const elemKind = fieldKind === "Array" ? kind(type.slice(2)) : undefined;
    const elem = elemKind === "Doc" || elemKind === "DocList" || elemKind === "Array" ? "Any" : elemKind;
    return `FieldSpec { name: ${JSON.stringify(field.name)}, go_type: ${JSON.stringify(type)}, kind: FieldKind::${fieldKind}, nullable: ${field.type.startsWith("*")}, elem: ${elem ? `Some(Elem::${elem})` : "None"} }`;
};
const enums = `#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum FieldKind { Str, I32, I64, U32, U64, Bool, Doc, DocList, Array, Object, Any }\n\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Elem { Str, I32, I64, U32, U64, Bool, Object, Any }\n\npub struct FieldSpec { pub name: &'static str, pub go_type: &'static str, pub kind: FieldKind, pub nullable: bool, pub elem: Option<Elem> }\n`;
const reachable = new Set();
const addStruct = name => {
    name = base(name);
    if (name.startsWith("[]")) return addStruct(name.slice(2));
    if (kind(name) !== "Object" || !schema.structs[name] || reachable.has(name)) return;
    reachable.add(name);
    for (const field of fields(name)) addStruct(field.type);
};
for (const type of Object.values(schema.methods)) {
    for (const field of fields(type)) addStruct(field.type);
}
// Merge identical field lists into one pattern. Empty lists use the fallback arm.
const groupedArms = entries => {
    const groups = new Map();
    for (const [name, type] of entries) {
        const body = fields(type).map(emitField).join(",\n");
        if (!body) continue;
        const names = groups.get(body) ?? [];
        names.push(JSON.stringify(name));
        groups.set(body, names);
    }
    return [...groups].map(([body, names]) => `${names.join(" | ")} => &[${body}],`);
};
const methodLines = groupedArms(Object.entries(schema.methods).sort(([a], [b]) => a.localeCompare(b)));
const structLines = groupedArms([...reachable].sort().map(name => [name, name]));
const output = `// Generated by node tools/gen-api-params/generate.mjs from the pinned Go protocol AST.\n${enums}\npub fn params_fields(method: &str) -> &'static [FieldSpec] { match method {\n${methodLines.join("\n")}\n_ => &[], } }\npub fn struct_fields(name: &str) -> &'static [FieldSpec] { match name {\n${structLines.join("\n")}\n_ => &[], } }\n`;
fs.writeFileSync(path.join(root, "crates/tsrs_api/src/paramfields.rs"), output);
execFileSync("rustfmt", ["--edition", "2024", path.join(root, "crates/tsrs_api/src/paramfields.rs")]);
console.log(`generated ${Object.keys(schema.methods).length} methods (${methodLines.length} field groups) and ${reachable.size} nested structs`);
